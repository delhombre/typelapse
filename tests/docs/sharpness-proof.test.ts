import { readFileSync, statSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * The landing's sharpness proof has to stay reproducible and has to stay true.
 *
 * The section prints two decibel figures and two file sizes beside two crops.
 * All of it comes from `pnpm sharpness:render`, which writes the crops and the
 * manifest together. These are the facts that would catch the proof going
 * stale: the payload is a real project, the manifest describes the PNGs on
 * disk, the crop the script would take today is the crop the manifest records,
 * and each file is the codec and chroma its label claims.
 */

const ROOT = resolve(__dirname, "../..");
const DIR = resolve(ROOT, "docs/sharpness");
const PROJECT = JSON.parse(readFileSync(resolve(DIR, "sharpness.project.json"), "utf8"));
const MANIFEST = JSON.parse(readFileSync(resolve(DIR, "sharpness.json"), "utf8"));
const SCRIPT = readFileSync(resolve(ROOT, "scripts/render-sharpness.mjs"), "utf8");

/** Width and height of a PNG, read from its IHDR chunk (bytes 16..23, big-endian). */
function pngSize(path: string): { width: number; height: number } {
	const bytes = readFileSync(path);
	expect(bytes.subarray(1, 4).toString("ascii")).toBe("PNG");
	return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
}

function file(format: string) {
	const entry = MANIFEST.files.find((candidate: { format: string }) => candidate.format === format);
	expect(entry, `the manifest should measure the ${format}`).toBeDefined();
	return entry;
}

describe("the sharpness proof", () => {
	it("is rendered from a committed project, not from a memory", () => {
		expect(MANIFEST.project).toBe("sharpness.project.json");
		// The export refuses fewer than two steps; two identical ones make a still.
		expect(PROJECT.steps).toHaveLength(2);
		expect(PROJECT.steps[0].code).toBe(PROJECT.steps[1].code);
		expect(PROJECT.width).toBe(1920);
		expect(PROJECT.height).toBe(1080);
		expect(PROJECT.typewriter).toBe(false);
	});

	it("is regenerated by one pnpm script", () => {
		const pkg = JSON.parse(readFileSync(resolve(ROOT, "package.json"), "utf8"));

		expect(pkg.scripts["sharpness:render"]).toBe("tsx scripts/render-sharpness.mjs");
	});

	it("records the frame and the crop the script takes today", () => {
		const crop = SCRIPT.match(
			/const CROP = \{ x: (\d+), y: (\d+), width: (\d+), height: (\d+) \};/,
		)?.slice(1);
		const frame = SCRIPT.match(/const FRAME = (\d+);/)?.[1];

		expect(crop?.map(Number)).toEqual([
			MANIFEST.crop.x,
			MANIFEST.crop.y,
			MANIFEST.crop.width,
			MANIFEST.crop.height,
		]);
		expect(Number(frame)).toBe(MANIFEST.frame);
	});

	it("ships the crops that manifest describes", () => {
		for (const entry of MANIFEST.files) {
			expect(pngSize(resolve(DIR, entry.crop))).toEqual({
				width: MANIFEST.crop.width,
				height: MANIFEST.crop.height,
			});
			expect(entry.width).toBe(PROJECT.width);
			expect(entry.height).toBe(PROJECT.height);
			expect(MANIFEST.crop.x + MANIFEST.crop.width).toBeLessThanOrEqual(entry.width);
			expect(MANIFEST.crop.y + MANIFEST.crop.height).toBeLessThanOrEqual(entry.height);
			expect(MANIFEST.frame).toBeLessThan(entry.frames);
		}
	});

	it("compares the files its labels name", () => {
		const webm = file("webm");
		const mp4 = file("mp4");

		expect([webm.codecName, webm.profile, webm.pixFmt]).toEqual(["av1", "High", "yuv444p"]);
		// yuvj420p is the same 4:2:0 at full range, which some Chromium builds write.
		expect([mp4.codecName, mp4.pixFmt.replace(/^yuvj/, "yuv")]).toEqual(["h264", "yuv420p"]);
		expect(webm.frames).toBe(mp4.frames);
		expect(webm.psnr).toBeGreaterThan(mp4.psnr);
	});

	/** Two small PNGs make the point; the page should not pay a video for it. */
	it("keeps both assets under 1.5 MB together", () => {
		const total = MANIFEST.files.reduce(
			(sum: number, entry: { crop: string }) => sum + statSync(resolve(DIR, entry.crop)).size,
			0,
		);

		expect(total).toBeLessThan(1.5 * 1024 * 1024);
	});
});
