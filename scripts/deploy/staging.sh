#!/usr/bin/env bash
# The shell of .github/workflows/deploy-staging.yaml, one subcommand per step:
#
#   staging.sh apply-secrets | apply-configmap | suspend-workers | release-job |
#              apply-workloads | rollout | smoke | resume-workers | show-state
#
# Every call to the cluster goes through kube(), which retries connection
# errors. Two real runs (#286) died on one dropped request each, on an
# application that was fine: "rpc error: invalid connection" inside a polling
# loop, and "dial tcp: i/o timeout" fetching the openapi document.
#
# kube() rules:
#   - up to 5 attempts, waiting 2, 4, 8 then 16 s between them;
#   - retries only when kubectl's stderr names a connection error (invalid
#     connection, i/o timeout, TLS handshake timeout, connection refused, EOF);
#   - never retries an answer from the API server ("Error from server (Invalid)",
#     Forbidden, NotFound...): the request arrived and was refused, so asking
#     again changes nothing;
#   - stdout passes through untouched; stderr is replayed on every attempt;
#   - kube_in() does the same for a call that reads a manifest on stdin, and
#     feeds it again on every attempt (a pipe is empty the second time).
#
# Environment: NAMESPACE (every step but apply-configmap, apply-workloads),
# RUNNER_TEMP, GITHUB_RUN_ID and GITHUB_RUN_ATTEMPT, all set by the workflow or
# the runner. Tests override KUBE_ATTEMPTS and SMOKE_TIMEOUT_SECONDS.

set -euo pipefail

KUBE_ATTEMPTS="${KUBE_ATTEMPTS:-5}"
KUBE_BACKOFF=(2 4 8 16)

kube_sleep() {
  sleep "$1"
}

# $1: a file holding kubectl's stderr.
kube_is_transient() {
  if grep -Eq 'Error from server \(' "$1"; then
    return 1
  fi
  grep -Eiq 'invalid connection|i/o timeout|TLS handshake timeout|connection refused|(^|[^[:alnum:]])EOF([^[:alnum:]]|$)' "$1"
}

# $1: "stdin" to feed $2 to kubectl on every attempt, anything else for none.
_kube_run() {
  local mode=$1 input=$2
  shift 2
  local err rc attempt=1 delay
  err="$(mktemp)"
  while :; do
    rc=0
    if [ "$mode" = stdin ]; then
      kubectl "$@" <<<"$input" 2>"$err" || rc=$?
    else
      kubectl "$@" </dev/null 2>"$err" || rc=$?
    fi
    cat "$err" >&2
    if [ "$rc" -eq 0 ]; then
      rm -f "$err"
      return 0
    fi
    if ! kube_is_transient "$err"; then
      rm -f "$err"
      return "$rc"
    fi
    if [ "$attempt" -ge "$KUBE_ATTEMPTS" ]; then
      echo "kube: giving up after $attempt attempts" >&2
      rm -f "$err"
      return "$rc"
    fi
    delay="${KUBE_BACKOFF[$((attempt - 1))]}"
    echo "kube: attempt $attempt/$KUBE_ATTEMPTS failed on a connection error, retrying in ${delay}s" >&2
    kube_sleep "$delay"
    attempt=$((attempt + 1))
  done
}

kube() {
  _kube_run none "" "$@"
}

# $1: the manifest to feed on stdin; the rest: the kubectl arguments.
kube_in() {
  local input=$1
  shift
  _kube_run stdin "$input" "$@"
}

# kubectl in the staging namespace.
kn() {
  kube -n "$NAMESPACE" "$@"
}

rendered() {
  echo "$RUNNER_TEMP/rendered/$1"
}

WORKERS=(typelapse-render-worker typelapse-deletion-worker)
SECRETS_ENVFILE=""
SMOKE_JOBS=()

# The Secret is built from an env file that exists only in RUNNER_TEMP (mode
# 600, removed on exit). The manifest it produces stays in a shell variable and
# reaches kubectl on stdin, so no second copy of the values touches the disk.
# Nothing is echoed, and the values are already masked by GitHub.
step_apply_secrets() {
  umask 077
  local name manifest
  # Global, not local: the EXIT trap runs after this function has returned.
  SECRETS_ENVFILE="$(mktemp "$RUNNER_TEMP/envfile.XXXXXX")"
  trap 'rm -f "$SECRETS_ENVFILE"' EXIT
  for name in DATABASE_URL BETTER_AUTH_SECRET R2_ACCESS_KEY_ID R2_SECRET_ACCESS_KEY POLAR_ACCESS_TOKEN POLAR_WEBHOOK_SECRET SMTP_URL; do
    if [ -z "${!name:-}" ]; then
      echo "::error::The Environment secret $name is not set"
      exit 1
    fi
    printf '%s=%s\n' "$name" "${!name}" >> "$SECRETS_ENVFILE"
  done
  if [ -n "${TYPELAPSE_GITHUB_TOKEN:-}" ]; then
    printf '%s=%s\n' TYPELAPSE_GITHUB_TOKEN "$TYPELAPSE_GITHUB_TOKEN" >> "$SECRETS_ENVFILE"
  fi
  # Server-side apply keeps the values out of the last-applied-configuration
  # annotation; --force-conflicts takes the fields back from any other manager
  # (a hand-made `kubectl create secret`).
  #
  # --validate=false: kubectl otherwise downloads the cluster's openapi document
  # to validate client-side, and that one request failed a run on an i/o timeout
  # (#286). The manifest is generated by kubectl itself from a fixed shape, and
  # the server validates it again on apply, so nothing is lost.
  manifest="$(kn create secret generic typelapse-env \
    --from-env-file="$SECRETS_ENVFILE" --dry-run=client -o yaml)"
  kube_in "$manifest" apply --server-side --force-conflicts --validate=false -f -
  # Absent only when the package is public (GHCR_PACKAGE_PUBLIC=true).
  if [ -n "${GHCR_PULL_TOKEN:-}" ]; then
    manifest="$(kn create secret docker-registry ghcr-secret \
      --docker-server=ghcr.io --docker-username="$GHCR_PULL_USER" \
      --docker-password="$GHCR_PULL_TOKEN" --dry-run=client -o yaml)"
    kube_in "$manifest" apply --server-side --force-conflicts --validate=false -f -
  fi
}

step_apply_configmap() {
  kube apply -f "$(rendered configmap.yaml)"
}

# Both workers are CronJobs that drain the queue and exit. Suspend them so no
# new pod starts during the release, then wait for the Jobs already created to
# finish. They stay suspended if anything after this fails; resume-workers is
# the only thing that unsuspends them. Absent on the first deploy, so each patch
# is skipped then.
step_suspend_workers() {
  local cronjob present deadline unfinished=""
  for cronjob in "${WORKERS[@]}"; do
    # --ignore-not-found makes "absent" an empty answer, so a failed request is
    # not mistaken for a missing CronJob.
    present="$(kn get "cronjob/$cronjob" --ignore-not-found -o name)"
    if [ -n "$present" ]; then
      kn patch "cronjob/$cronjob" --type merge -p '{"spec":{"suspend":true}}'
    fi
  done
  # A worker Job is still unfinished while it has no completionTime and no
  # Failed condition. Testing status.active alone would miss a Job the CronJob
  # created an instant before the patch, whose pod does not exist yet. A render
  # may legitimately run for a while (TYPELAPSE_RENDER_TIMEOUT_MS is 15 minutes
  # by default), so the wait is bounded at 20.
  deadline=$((SECONDS + 1200))
  while [ "$SECONDS" -lt "$deadline" ]; do
    unfinished="$(kn get jobs \
      -l 'app in (typelapse-render-worker,typelapse-deletion-worker)' -o json \
      | jq -r '.items[]
          | select((.status.completionTime // "") == "")
          | select([.status.conditions[]? | select(.type == "Failed" and .status == "True")] | length == 0)
          | .metadata.name')"
    if [ -z "$unfinished" ]; then
      echo "No worker Job is running"
      return 0
    fi
    echo "Waiting for: $unfinished"
    sleep 10
  done
  echo "::error::A worker Job was still running after 20 minutes ($unfinished). The workers are suspended; re-run the deploy once it has finished."
  exit 1
}

release_diagnose() {
  echo "::error::$1"
  kn describe job typelapse-release || true
  kn get pods -l job-name=typelapse-release || true
  kn describe pods -l job-name=typelapse-release || true
  echo "Last 30 events:"
  { kn get events --sort-by=.lastTimestamp | tail -n 30; } || true
  kn logs job/typelapse-release --all-containers --tail=200 || true
}

# A Job's pod template is immutable, so the previous one goes first.
step_release_job() {
  local deadline status waiting refused
  kn delete job typelapse-release --ignore-not-found --wait=true
  kube apply -f "$(rendered release-job.yaml)"
  # `kubectl wait` only knows one condition, so a failed Job would sit out the
  # whole timeout. Poll the counters, and the pod's waiting reason so a bad
  # image fails in seconds, not after the timeout.
  deadline=$((SECONDS + 660))
  while [ "$SECONDS" -lt "$deadline" ]; do
    status="$(kn get job typelapse-release -o jsonpath='{.status.succeeded}/{.status.failed}')"
    case "$status" in
      1/*) echo "Release Job succeeded"; return 0 ;;
      */[1-9]*) release_diagnose "Release Job failed"; exit 1 ;;
    esac
    waiting="$(kn get pods -l job-name=typelapse-release \
      -o jsonpath='{.items[*].status.containerStatuses[*].state.waiting.reason}')"
    case "$waiting" in
      *ErrImagePull*|*ImagePullBackOff*|*InvalidImageName*)
        release_diagnose "Release Job cannot pull its image ($waiting). Check GHCR_PULL_TOKEN and that the build pushed this tag."
        exit 1 ;;
    esac
    # The Job controller could not create the pod at all: quota or admission
    # refused it.
    refused="$(kn get events \
      --field-selector involvedObject.kind=Job,involvedObject.name=typelapse-release,reason=FailedCreate \
      -o jsonpath='{.items[*].message}')"
    if [ -n "$refused" ]; then
      release_diagnose "The release pod was refused: $refused"
      exit 1
    fi
    sleep 5
  done
  release_diagnose "Release Job did not finish in 11 minutes"
  exit 1
}

# The CronJobs are applied suspended (suspend: true in the manifests).
step_apply_workloads() {
  local file
  for file in api render-worker deletion-worker ingress; do
    kube apply -f "$(rendered "$file.yaml")"
  done
}

# Timeout sized for the managed cluster's small (2 vCPU / 4 GB) nodes: an image
# pull plus a cold start is slow there.
step_rollout() {
  kn rollout status deployment/typelapse-api --timeout=420s
}

# Smoke Jobs a failed run left behind (a Job still running at the bound is kept
# on purpose, see step_smoke). Anything named smoke-* and over an hour old has
# long outlived its activeDeadlineSeconds, so it goes before new ones are made.
# Best effort: a cluster that cannot list Jobs will fail the next call anyway,
# with a clearer message.
delete_stale_smoke_jobs() {
  local json stale job
  if ! json="$(kn get jobs -o json)"; then
    echo "Could not list Jobs to clean up old smoke Jobs; continuing"
    return 0
  fi
  stale="$(printf '%s' "$json" | jq -r --argjson cutoff "$(($(date +%s) - 3600))" \
    '.items[]
      | select(.metadata.name | startswith("smoke-"))
      | select((.metadata.creationTimestamp | fromdateiso8601) < $cutoff)
      | .metadata.name')"
  for job in $stale; do
    echo "Deleting stale smoke Job $job (older than one hour)"
    kn delete job "$job" --ignore-not-found --wait=false || true
  done
}

smoke_report() {
  echo "::error::$1"
  kn describe job "$2" || true
  kn describe pods -l "job-name=$2" || true
  kn logs "job/$2" --all-containers --tail=200 || true
}

# Print the state of one smoke Job: done, failed, pull <reason>, refused
# <message> or waiting. Returns 1 when the cluster could not be asked, so the
# caller can count the poll as lost and ask again.
smoke_poll() {
  local job=$1 status waiting refused
  status="$(kn get job "$job" -o jsonpath='{.status.succeeded}/{.status.failed}')" || return 1
  case "$status" in
    1/*) echo "done"; return 0 ;;
    */[1-9]*) echo failed; return 0 ;;
  esac
  waiting="$(kn get pods -l "job-name=$job" \
    -o jsonpath='{.items[*].status.containerStatuses[*].state.waiting.reason}')" || return 1
  case "$waiting" in
    *ErrImagePull*|*ImagePullBackOff*|*InvalidImageName*) echo "pull $waiting"; return 0 ;;
  esac
  refused="$(kn get events \
    --field-selector "involvedObject.kind=Job,involvedObject.name=$job,reason=FailedCreate" \
    -o jsonpath='{.items[*].message}')" || return 1
  if [ -n "$refused" ]; then
    echo "refused $refused"
    return 0
  fi
  echo waiting
}

# Delete only Jobs that have finished, whatever the outcome. Runs as the EXIT
# trap, after step_smoke has returned, hence the global SMOKE_JOBS.
smoke_cleanup() {
  local job status
  for job in ${SMOKE_JOBS[@]+"${SMOKE_JOBS[@]}"}; do
    status="$(kn get job "$job" -o jsonpath='{.status.succeeded}/{.status.failed}' 2>/dev/null || true)"
    case "$status" in
      1/*|*/[1-9]*) kn delete job "$job" --ignore-not-found --wait=false || true ;;
      *) echo "Leaving $job in place: it has not finished." ;;
    esac
  done
}

# Run each worker once, by hand, from its (still suspended) CronJob, to prove
# the pod starts and exits cleanly: image, secret, database URL, PriorityClass
# and quota. On an empty queue drain mode exits 0 in seconds. A queued job is
# worked for real, so the bound (1000 s) sits above the render timeout
# (TYPELAPSE_RENDER_TIMEOUT_MS, 900 s). A Job still running at the bound is NOT
# deleted: it may be a real render. The next deploy waits for it before it
# migrates, and the Job's own activeDeadlineSeconds ends it.
#
# A poll that fails after kube()'s retries is counted and logged, not fatal: the
# step fails on a Job that reports failure or on the deadline, never on the API
# having a bad minute.
step_smoke() {
  local run="${GITHUB_RUN_ID}-${GITHUB_RUN_ATTEMPT}" timeout="${SMOKE_TIMEOUT_SECONDS:-1000}"
  local pending=() still=() cronjob job outcome deadline lost=0
  trap smoke_cleanup EXIT
  delete_stale_smoke_jobs
  for cronjob in "${WORKERS[@]}"; do
    job="smoke-${cronjob#typelapse-}-$run"
    # A retried create that the first attempt had already completed answers
    # AlreadyExists, which is not a failure.
    if ! kn create job "$job" --from="cronjob/$cronjob"; then
      kn get job "$job" > /dev/null
    fi
    SMOKE_JOBS+=("$job")
  done
  deadline=$((SECONDS + timeout))
  pending=("${SMOKE_JOBS[@]}")
  while [ "$SECONDS" -lt "$deadline" ] && [ "${#pending[@]}" -gt 0 ]; do
    still=()
    for job in "${pending[@]}"; do
      if ! outcome="$(smoke_poll "$job")"; then
        lost=$((lost + 1))
        echo "Smoke poll of $job failed ($lost lost so far), continuing"
        still+=("$job")
        continue
      fi
      case "$outcome" in
        done) echo "$job completed" ;;
        failed) smoke_report "$job failed" "$job"; exit 1 ;;
        pull*) smoke_report "$job cannot pull its image (${outcome#pull })" "$job"; exit 1 ;;
        refused*) smoke_report "$job was refused: ${outcome#refused }" "$job"; exit 1 ;;
        *) still+=("$job") ;;
      esac
    done
    pending=(${still[@]+"${still[@]}"})
    sleep 5
  done
  if [ "$lost" -gt 0 ]; then
    echo "Smoke polls lost to API errors and absorbed: $lost"
  fi
  if [ "${#pending[@]}" -gt 0 ]; then
    for job in "${pending[@]}"; do
      smoke_report "$job did not finish in $timeout s; it is left running in case it is a real render" "$job"
    done
    exit 1
  fi
}

step_resume_workers() {
  local cronjob
  for cronjob in "${WORKERS[@]}"; do
    kn patch "cronjob/$cronjob" --type merge -p '{"spec":{"suspend":false}}'
  done
}

step_show_state() {
  kn get pods,cronjob,jobs -o wide || true
  echo "::group::typelapse-api"
  kn logs deployment/typelapse-api --tail=100 || true
  echo "::endgroup::"
}

main() {
  case "${1:-}" in
    apply-secrets) step_apply_secrets ;;
    apply-configmap) step_apply_configmap ;;
    suspend-workers) step_suspend_workers ;;
    release-job) step_release_job ;;
    apply-workloads) step_apply_workloads ;;
    rollout) step_rollout ;;
    smoke) step_smoke ;;
    resume-workers) step_resume_workers ;;
    show-state) step_show_state ;;
    *)
      echo "usage: staging.sh apply-secrets|apply-configmap|suspend-workers|release-job|apply-workloads|rollout|smoke|resume-workers|show-state" >&2
      exit 2 ;;
  esac
}

if [ "${BASH_SOURCE[0]}" = "$0" ]; then
  main "$@"
fi
